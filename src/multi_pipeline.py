"""
src/multi_pipeline.py
Multi-camera occupancy detection pipeline.

Runs ANY number of cameras at once in ONE program:
  • One shared YOLOv8 detector        (only one model loaded, saves memory)
  • One tracker + one seat map PER camera
  • One shared temporal engine + one shared CSV log

PERFORMANCE (important on CPU / many cameras)
---------------------------------------------
Two knobs, both set from run_dual.py:
  --every N   : only run detection every N-th frame (default 2).
                In between, the last annotated frame is reused.
                Higher = faster but choppier. People don't move that
                fast, so 2 or 3 is usually invisible for occupancy.
  --imgsz S   : shrink each frame to S pixels before the model looks
                (e.g. 320). Smaller = much faster, slightly less precise.

OVERLAPPING CAMERAS
-------------------
Each seat is "owned" by one camera (ID auto-prefixed cam0_, cam1_, ...).
Draw each physical desk's box on only ONE camera to avoid double counting.

To share a desk that's visible to more than one camera, do NOT hand-edit
the seat JSON files. Instead declare it in config/settings.yaml:

    seats:
      shared_seats:
        - global_id: "desk1"
          cameras:
            cam0: "seat_03"   # the raw auto-generated id drawn on cam0
            cam1: "seat_01"   # the raw auto-generated id drawn on cam1

Both entries get remapped to "global_desk1" at startup, registered ONCE
in the shared temporal engine, and counted as occupied if EITHER camera
sees a person there (a simple set-union, so no double vote is possible).
Any shared_seats entry that doesn't match a real drawn seat on the named
camera is reported as a warning at startup so typos surface immediately.

PERSON-DRIVEN AUTO-DISCOVERY (experimental, alternative to the above)
-----------------------------------------------------------------------
If face_recognition.auto_enroll is on, the pipeline also watches for the
same recognised identity showing up on two different camera-local seats
at the same time. After 5 consecutive ticks of this, it infers the two
seats are actually one physical desk and merges them automatically —
no config needed. This runs alongside the manual shared_seats mechanism,
never overrides it, and only ever considers seat pairs from DIFFERENT
cameras that aren't already merged some other way. It's meant to
demonstrate the trade-off between seat-level (ROI-based, deterministic,
configured once) and person-level (identity-based, adapts automatically,
but only as reliable as face matching across camera angles) merging —
not to replace the manual mechanism for anything that needs to be
reliably correct in a demo.

Run via run_dual.py (project root):
    python run_dual.py --sources 0 1 --no-face
    python run_dual.py --sources 0 1 --no-face --every 3 --imgsz 320
"""
