class MultiCameraPipeline:
    """Runs all cameras in a single loop and writes one combined log."""

    WARMUP_FRAMES = 30

    def __init__(self, cfg: Config, sources: list, process_every: int = 2,
                 save_video: bool = False, log_resources: bool = False):
        self.cfg = cfg
        self._frame_id = 0
        self._running = False
        self.process_every = max(1, int(process_every))

        # Annotated video recording (one .mp4 per camera) - see _record()
        self.save_video = save_video
        self._writers: dict[str, cv2.VideoWriter] = {}
        self._writer_sizes: dict[str, tuple[int, int]] = {}
        self._video_paths: list[Path] = []
        self._loop_times: list[float] = []
        self._video_fps: float | None = None

        # Live cost logging (CPU / RAM / per-stage ms) - see src/resource_monitor.py
        self.log_resources = log_resources
        self._counters = None
        self._monitor = None

        # Test-step markers: press 1-9 (0 = between steps) in a camera window
        self._step: str | None = None
        self._markers_path: Path | None = None

        weights = cfg.model.custom_weights or cfg.model.weights
        self.detector = YOLOv8Detector(
            weights=weights,
            confidence=cfg.model.confidence_threshold,
            iou_threshold=cfg.model.iou_threshold,
            device=cfg.model.device,
            imgsz=cfg.model.imgsz,
        )

        self._face_rec_enabled = cfg.face_recognition.enabled
        self.face_rec = FaceRecogniser(
            known_faces_dir=cfg.face_recognition.known_faces_dir,
            model_name=cfg.face_recognition.model,
            detector_backend=cfg.face_recognition.detector_backend,
            distance_metric=cfg.face_recognition.distance_metric,
            threshold=cfg.face_recognition.threshold,
            min_face_size=cfg.face_recognition.min_face_size,
            auto_enroll=cfg.face_recognition.get("auto_enroll", False),
            face_region_top_fraction=cfg.face_recognition.get("face_region_top_fraction", 0.5),
        )

        self.temporal = TemporalInferenceEngine(
            window_size=cfg.temporal.window_size,
            occupied_threshold=cfg.temporal.occupied_threshold,
            cooldown_frames=cfg.temporal.cooldown_frames,
        )
        self.occ_logger = OccupancyLogger(
            output_dir=cfg.io.output_dir,
            log_interval_sec=cfg.io.log_interval_seconds,
        )

        # Built once, shared read-only by every camera worker.
        self.shared_seat_lookup = build_shared_seat_lookup(cfg)

        # EXPERIMENTAL: person-driven auto-discovery of shared desks.
        # Alternative to the manual click-to-pair mechanism above — if the
        # same recognised face identity is seen occupying two different
        # camera-local seats at the same time, repeatedly, infer they're
        # the same physical desk and merge them automatically. Runs
        # alongside the manual mechanism, never overrides it: seats already
        # merged via shared_seat_lookup never reach this code (they already
        # share one seat_id by the time the main loop runs).
        self.auto_discovered_lookup: dict[str, str] = {}
        self._co_occurrence: dict[str, int] = {}
        self._auto_merge_log: list[tuple[str, str, str, str]] = []
        self._auto_merge_threshold = 5   # consecutive ticks required before merging

        self.workers = [
            CameraWorker(i, src, cfg, self.shared_seat_lookup)
            for i, src in enumerate(sources)
        ]
        logger.info(f"[MultiPipeline] {len(self.workers)} camera(s), "
                    f"detecting every {self.process_every} frame(s), "
                    f"imgsz={cfg.model.imgsz}")

    # -- Seat setup --

    def setup_all_seats(self) -> None:
        for w in self.workers:
            for _ in range(self.WARMUP_FRAMES):
                w.read()
            ret, frame = w.read()
            if not ret:
                raise RuntimeError(f"[{w.prefix}] Could not read a frame for seat setup.")
            seat_ids = w.setup_seats(frame)
            self.temporal.register_seats(seat_ids)
            logger.info(f"[{w.prefix}] Registered {len(seat_ids)} seat(s)")

        logger.info(f"[MultiPipeline] Total unique seats tracked: "
                    f"{self.temporal.total_seats}")

        # Catch config typos: any shared_seats entry that never matched a
        # real drawn seat on the camera it named.
        all_matched = set().union(*(w.matched_shared_keys for w in self.workers)) \
            if self.workers else set()
        unmatched = set(self.shared_seat_lookup.keys()) - all_matched
        for cam_prefix, local_id in sorted(unmatched):
            logger.warning(
                f"[MultiPipeline] shared_seats config expects '{local_id}' on "
                f"'{cam_prefix}' but no such seat was found — check settings.yaml "
                f"against output/seats_{cam_prefix}.json"
            )

    # -- Person-driven auto-discovery (experimental, alternative to manual pairing) --

    def _resolve_global_id(self, seat_id: str) -> str:
        """Map a raw camera-local seat_id to its auto-discovered global id,
        if one has been found. Seats already merged manually (shared_seat_lookup)
        never appear here since they were renamed before the main loop starts."""
        return self.auto_discovered_lookup.get(seat_id, seat_id)

    def _update_person_driven_merge(self, all_occupants: dict[str, str]) -> None:
        """
        If the same recognised identity is attributed to two different
        camera-local seats in the SAME tick, count it. After
        self._auto_merge_threshold consecutive ticks of this, merge those
        two seats into a new auto-discovered global seat — same effect as
        a manual shared_seats pairing, just inferred from behaviour instead
        of configured up front.

        Restricted to pairs from DIFFERENT cameras (same-camera duplicate
        attribution would mean a tracking glitch, not a shared desk) and
        skips anything already merged (manually or previously auto-merged).
        """
        by_identity: dict[str, list[str]] = {}
        for seat_id, identity in all_occupants.items():
            if identity and identity != "unknown":
                by_identity.setdefault(identity, []).append(seat_id)

        for identity, seat_ids in by_identity.items():
            if len(seat_ids) < 2:
                continue

            for i in range(len(seat_ids)):
                for j in range(i + 1, len(seat_ids)):
                    a, b = sorted([seat_ids[i], seat_ids[j]])
                    if a == b:
                        continue
                    if a.startswith(SHARED_SEAT_PREFIX) or b.startswith(SHARED_SEAT_PREFIX):
                        continue  # already a manually-merged seat
                    if a in self.auto_discovered_lookup or b in self.auto_discovered_lookup:
                        continue  # already auto-merged into something
                    if a.split("_")[0] == b.split("_")[0]:
                        continue  # same camera — not a cross-camera shared-desk candidate

                    pair_key = f"{a}|{b}"
                    self._co_occurrence[pair_key] = self._co_occurrence.get(pair_key, 0) + 1

                    if self._co_occurrence[pair_key] >= self._auto_merge_threshold:
                        global_id = f"auto_global_{len(self._auto_merge_log) + 1}"
                        self.auto_discovered_lookup[a] = global_id
                        self.auto_discovered_lookup[b] = global_id
                        self._auto_merge_log.append((a, b, identity, global_id))

                        self.temporal.register_seat(global_id)
                        self.temporal.remove_seat(a)
                        self.temporal.remove_seat(b)

                        logger.info(
                            f"[MultiPipeline] AUTO-DISCOVERED shared seat: "
                            f"'{a}' + '{b}' both occupied by '{identity}' for "
                            f"{self._auto_merge_threshold} consecutive ticks "
                            f"-> merged as '{global_id}'"
                        )

    # -- Main loop --

    def run(self) -> None:
        self.setup_all_seats()
        if self.log_resources:
            from src.resource_monitor import ResourceMonitor, StageCounters
            self._counters = StageCounters()
            self._monitor = ResourceMonitor(
                self._counters, self.cfg.io.output_dir, n_cams=len(self.workers),
                settings={
                    "device": self.cfg.model.device,
                    "imgsz": self.cfg.model.imgsz,
                    "process_every": self.process_every,
                    "face_enabled": bool(self._face_rec_enabled),
                    "sources": [str(w.source) for w in self.workers],
                },
            )
            self._monitor.start()
        self._running = True
        logger.info("[MultiPipeline] Running - press 'q' in any window to stop")

        while self._running:
            self._frame_id += 1
            do_detect = (self._frame_id % self.process_every == 0)

            # Always read every camera (keeps the live stream from backing up)
            grabbed = []
            for w in self.workers:
                ret, frame = w.read()
                grabbed.append((w, frame if ret else None))

            if all(frame is None for _, frame in grabbed):
                logger.info("[MultiPipeline] No cameras returning frames - stopping.")
                break

            if self._counters is not None:
                self._counters.add(loops=1, processed=1 if do_detect else 0)

            # -- Skipped frame: just re-show the last annotated image --
            if not do_detect:
                if self.cfg.display.show_window:
                    for w, frame in grabbed:
                        show = w.last_annotated if w.last_annotated is not None else frame
                        if show is not None:
                            cv2.imshow(w.window_name, show)
                    if self._handle_key(cv2.waitKey(1) & 0xFF):
                        self._running = False
                self._record(grabbed)
                continue

            # -- Full processing frame --
            per_cam = []
            all_occupied: set[str] = set()
            all_occupants: dict[str, str] = {}

            for w, frame in grabbed:
                if frame is None:
                    continue
                _t0 = time.perf_counter()
                detections = self.detector.detect(frame, extract_crops=True)
                _t1 = time.perf_counter()
                tracks = w.tracker.update(detections, frame)
                _t2 = time.perf_counter()

                if self._face_rec_enabled and self.face_rec.is_available():
                    for t in tracks:
                        if t.crop is not None:
                            t.face_identity = self.face_rec.identify_track(
                                t.track_id, t.crop
                            )
                _t3 = time.perf_counter()

                if self._counters is not None:
                    self._counters.add(
                        detect_ms=(_t1 - _t0) * 1000, detect_n=1,
                        track_ms=(_t2 - _t1) * 1000, track_n=1,
                        face_ms=(_t3 - _t2) * 1000,
                        people_sum=len(tracks), people_n=1,
                    )

                for t in tracks:
                    for seat in w.seat_mgr.match_person_to_seat(t.bbox):
                        all_occupied.add(seat.seat_id)
                        if t.face_identity and t.face_identity != "unknown":
                            all_occupants[seat.seat_id] = t.face_identity

                per_cam.append((w, frame, tracks))

            # Every camera contributes into ONE shared set before the
            # temporal engine sees anything. A shared "global_" seat_id
            # spotted by two cameras still appears only once here — this
            # is what prevents one person from being counted as two.
            #
            # Person-driven auto-discovery runs first, on the raw
            # (pre-merge) ids, then everything gets resolved through
            # whatever's been merged so far (manual pairs are already
            # collapsed at this point; auto-discovered pairs get resolved
            # here).
            self._update_person_driven_merge(all_occupants)
            all_occupied = {self._resolve_global_id(sid) for sid in all_occupied}
            all_occupants = {
                self._resolve_global_id(sid): identity
                for sid, identity in all_occupants.items()
            }

            states = self.temporal.update(all_occupied, all_occupants)

            # Recorded clips -> log clip time (s from start) instead of the
            # wall clock, so the log matches labels from label_ground_truth.py.
            # Clips recorded together with record_clips.py share a timeline,
            # so the first camera's position is used for all of them.
            clip_ts = None
            if all(w.is_file for w in self.workers):
                clip_ts = self.workers[0].clip_time()

            if self.cfg.io.save_occupancy_log:
                confidences = {
                    sid: buf.confidence for sid, buf in self.temporal._buffers.items()
                }
                self.occ_logger.log_frame(
                    frame_id=self._frame_id,
                    seat_states=states,
                    confidences=confidences,
                    occupants=all_occupants,
                    timestamp=clip_ts,
                )

            for w, frame, tracks in per_cam:
                for seat in w.seat_mgr.seats:
                    resolved_id = self._resolve_global_id(seat.seat_id)
                    seat.current_state = states.get(
                        resolved_id, SeatState.VACANT
                    ).value
                    seat.occupant_id = all_occupants.get(resolved_id)

                frame = w.seat_mgr.draw_on_frame(frame)
                frame = DeepSORTTracker.draw_tracks(frame, tracks)
                frame = self._draw_hud(w, frame, states)
                frame = self._draw_step(frame)
                w.last_annotated = frame

                if self.cfg.display.show_window:
                    cv2.imshow(w.window_name, frame)

            if self.cfg.display.show_window:
                if self._handle_key(cv2.waitKey(1) & 0xFF):
                    logger.info("[MultiPipeline] Quit requested.")
                    self._running = False

            self._record(grabbed)

        self.stop()

    # -- Test-step markers --

    STEP_LABELS = {
        "0": "Between steps",
        "1": "All empty -> expect 3 vacant",
        "2": "A sits in seat 1",
        "3": "B sits in seat 3 -> seat 2 must stay vacant",
        "4": "C sits in seat 2 -> all occupied",
        "5": "B leans back / rolls sideways",
        "6": "C stands behind A -> seat 2 vacant",
        "7": "A leaves, bag left on seat 1",
        "8": "Someone walks past -> no change",
        "9": "Everyone leaves -> 3 vacant",
    }

    def _handle_key(self, key: int) -> bool:
        """Returns True when the user asked to quit. Digits mark test steps."""
        if key == ord("q"):
            return True
        if ord("0") <= key <= ord("9"):
            self._mark_step(chr(key))
        return False

    def _mark_step(self, step: str) -> None:
        """
        Record the start of a test step: shown on screen + in the saved
        video, and written to output/markers_<time>.csv with the same kind
        of timestamp as the occupancy log (wall clock live, clip time for files).
        """
        import csv
        label = self.STEP_LABELS.get(step, "")
        self._step = step

        if all(w.is_file for w in self.workers):
            ts = self.workers[0].clip_time()
        else:
            ts = time.time()

        if self._markers_path is None:
            out_dir = Path(self.cfg.io.output_dir)
            out_dir.mkdir(parents=True, exist_ok=True)
            self._markers_path = out_dir / f"markers_{time.strftime('%Y%m%d_%H%M%S')}.csv"
            with open(self._markers_path, "w", newline="") as f:
                csv.writer(f).writerow(["timestamp", "time_of_day", "frame_id", "step", "label"])
            logger.info(f"[MultiPipeline] Step markers -> {self._markers_path}")

        with open(self._markers_path, "a", newline="") as f:
            csv.writer(f).writerow([round(ts, 3), time.strftime("%H:%M:%S"),
                                    self._frame_id, step, label])
        logger.info(f"[MultiPipeline] STEP {step}: {label}")

    def _draw_step(self, frame):
        """Banner under the HUD showing the current test step."""
        if self._step is None:
            return frame
        text = (f"STEP {self._step}: {self.STEP_LABELS.get(self._step, '')}"
                if self._step != "0" else "Between steps")
        (tw, th), _ = cv2.getTextSize(text, cv2.FONT_HERSHEY_SIMPLEX, 0.55, 1)
        cv2.rectangle(frame, (0, 80), (min(frame.shape[1], tw + 20), 80 + th + 14),
                      (0, 140, 255) if self._step != "0" else (90, 90, 90), -1)
        cv2.putText(frame, text, (10, 80 + th + 6),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 1)
        return frame

    # -- Annotated video recording --

    FPS_PROBE_LOOPS = 30   # live cameras: loops used to measure the real loop rate

    def _record(self, grabbed) -> None:
        """
        Write what each camera window is showing to output/annotated_camN.mp4,
        stamped with the time so it lines up with notes taken during a test.

        Live cameras: the loop runs slower than the camera's nominal fps
        (detection takes time), so the real loop rate is measured over the
        first FPS_PROBE_LOOPS loops and used as the video fps - otherwise
        the saved video would play back too fast. Those first ~few seconds
        are not saved. Video files: the source fps is used directly.
        """
        if not self.save_video:
            return

        if self._video_fps is None:
            if all(w.is_file for w in self.workers):
                self._video_fps = self.workers[0].cap.get(cv2.CAP_PROP_FPS) or 25.0
            else:
                self._loop_times.append(time.perf_counter())
                if len(self._loop_times) < self.FPS_PROBE_LOOPS:
                    return
                span = self._loop_times[-1] - self._loop_times[0]
                measured = (len(self._loop_times) - 1) / span if span > 0 else 10.0
                self._video_fps = max(1.0, min(60.0, measured))
            logger.info(f"[MultiPipeline] Saving annotated video at {self._video_fps:.1f} fps")

        out_dir = Path(self.cfg.io.output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)

        for w, frame in grabbed:
            src = w.last_annotated if w.last_annotated is not None else frame
            if src is None:
                continue
            img = src.copy()

            if w.prefix not in self._writers:
                h, wd = img.shape[:2]
                path = out_dir / f"annotated_{w.prefix}_{time.strftime('%Y%m%d_%H%M%S')}.mp4"
                self._writers[w.prefix] = cv2.VideoWriter(
                    str(path), cv2.VideoWriter_fourcc(*"mp4v"), self._video_fps, (wd, h)
                )
                self._writer_sizes[w.prefix] = (wd, h)
                self._video_paths.append(path)
                logger.info(f"[{w.prefix}] Recording annotated video -> {path}")

            size = self._writer_sizes[w.prefix]
            if (img.shape[1], img.shape[0]) != size:
                img = cv2.resize(img, size)

            stamp = (f"clip t={w.clip_time():7.1f}s" if w.is_file
                     else time.strftime("%Y-%m-%d %H:%M:%S"))
            y = img.shape[0] - 12
            cv2.putText(img, stamp, (10, y), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 0, 0), 3)
            cv2.putText(img, stamp, (10, y), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 1)
            self._writers[w.prefix].write(img)

    # -- Per-camera HUD --

    def _draw_hud(self, w: CameraWorker, frame, states: dict):
        """
        Two HUD lines:
          Line 1 (this camera's own view) — Seats / Occupied / Vacant counted
          from THIS camera's seat list only. If this camera owns a shared
          'global_' seat, that seat's status also appears in the OTHER
          camera's line 1 (by design — one shared desk, two views).

          Line 2 (site-wide proof of dedup) — "Raw (per-camera sum)" vs
          "Unique (deduped)". Raw is what you'd get by naively adding up
          every camera's own seat count, which double-counts any shared
          desk. Unique is self.temporal.total_seats, which merges shared
          desks down to one. When there's at least one shared desk, Raw
          will read higher than Unique — that gap IS the proof the merge
          is doing something, not just a number that happens to match.
        """
        win_w = frame.shape[1]
        cam_seats = [s.seat_id for s in w.seat_mgr.seats]
        occupied = sum(
            1 for sid in cam_seats
            if states.get(self._resolve_global_id(sid)) == SeatState.OCCUPIED
        )
        total = len(cam_seats)
        vacant = total - occupied

        raw_total = sum(len(worker.seat_mgr.seats) for worker in self.workers)
        unique_total = self.temporal.total_seats
        unique_occupied = self.temporal.occupied_count

        overlay = frame.copy()
        cv2.rectangle(overlay, (0, 0), (win_w, 76), (20, 20, 20), -1)
        cv2.addWeighted(overlay, 0.65, frame, 0.35, 0, frame)

        line1 = (f"{w.window_name}  |  Seats: {total}  "
                 f"Occupied: {occupied}  Vacant: {vacant}")
        cv2.putText(frame, line1, (10, 30),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.58, (220, 220, 220), 1)

        dedup_color = (0, 200, 255) if raw_total != unique_total else (150, 220, 150)
        line2 = (f"Site-wide  |  Raw: {raw_total}  ->  "
                 f"Unique: {unique_total}  ({unique_occupied} occupied)")
        cv2.putText(frame, line2, (10, 60),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.58, dedup_color, 1)
        return frame

    # -- Cleanup --

    def stop(self) -> None:
        self._running = False
        if self._monitor is not None:
            try:
                self._monitor.stop()
            except Exception as e:          # never let logging block saving videos/logs
                logger.warning(f"[MultiPipeline] Resource monitor stop failed: {e}")
            self._monitor = None
        for w in self.workers:
            w.release()
        for wr in self._writers.values():
            wr.release()
        self._writers.clear()
        for path in self._video_paths:
            logger.info(f"[MultiPipeline] Annotated video saved -> {path}")
        if self._markers_path:
            logger.info(f"[MultiPipeline] Step markers saved -> {self._markers_path}")
        cv2.destroyAllWindows()

        summary_path = self.occ_logger.save_summary()
        logger.info(f"[MultiPipeline] Summary -> {summary_path}")
        if self._auto_merge_log:
            logger.info(f"[MultiPipeline] Auto-discovered {len(self._auto_merge_log)} "
                        f"shared seat(s) via person-driven matching:")
            for a, b, identity, global_id in self._auto_merge_log:
                logger.info(f"    '{a}' + '{b}' (matched via '{identity}') -> '{global_id}'")
        logger.info(f"[MultiPipeline] Session ended. "
                    f"Logged {self.occ_logger.record_count} records. "
                    f"Site-wide unique seats: {self.temporal.total_seats}")