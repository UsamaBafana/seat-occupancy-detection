def _is_video_file(source) -> bool:
    """True for a recorded clip path (not a camera index or a network stream)."""
    s = str(source).strip()
    return not s.isdigit() and not s.lower().startswith(("rtsp://", "rtmp://", "http://", "https://"))


SHARED_SEAT_PREFIX = "global_"
SHARED_SEATS_FILE = Path("config/shared_seats.yaml")


# -------------------------------------------------------------
#  Shared-seat config helper
# -------------------------------------------------------------

def build_shared_seat_lookup(cfg: Config) -> dict[tuple[str, str], str]:
    """
    Reads the shared-desk mapping and returns:
      (camera_prefix, raw_local_seat_id) -> global_seat_id

    Checks TWO sources, in order:
      1. config/shared_seats.yaml — auto-generated by map_shared_seat.py
         (click-to-pair tool). Preferred: settings.yaml is never touched.
      2. cfg.seats.shared_seats in settings.yaml — manual fallback, kept
         for backward compatibility if entries were typed there directly.

    Example entry (same shape in either source):
      - global_id: "desk1"
        cameras:
          cam0: "seat_03"
          cam1: "seat_01"
    """
    lookup: dict[tuple[str, str], str] = {}
    source_desc = None

    if SHARED_SEATS_FILE.exists():
        import yaml
        with open(SHARED_SEATS_FILE) as f:
            data = yaml.safe_load(f) or {}
        shared = data.get("shared_seats", []) or []
        source_desc = str(SHARED_SEATS_FILE)
    else:
        shared = cfg.seats.get("shared_seats", []) or []
        if shared:
            source_desc = "settings.yaml"

    for entry in shared:
        global_id = entry["global_id"]
        if not global_id.startswith(SHARED_SEAT_PREFIX):
            global_id = f"{SHARED_SEAT_PREFIX}{global_id}"

        for cam_prefix, local_seat_id in entry.get("cameras", {}).items():
            lookup[(cam_prefix, local_seat_id)] = global_id

    if lookup:
        logger.info(f"[MultiPipeline] {len(lookup)} camera-local seat(s) "
                    f"mapped to shared global desks from {source_desc}")

    return lookup


