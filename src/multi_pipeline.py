#  Per-camera state holder
# -------------------------------------------------------------

class CameraWorker:
    """Everything that belongs to a single camera: its feed, tracker, seats."""

    def __init__(
        self,
        cam_id: int,
        source,
        cfg: Config,
        shared_seat_lookup: dict[tuple[str, str], str] | None = None,
    ):
        self.cam_id = cam_id
        self.prefix = f"cam{cam_id}"
        self.source = source
        self.cfg = cfg
        self.window_name = f"Camera {cam_id}"
        self.last_annotated = None      # reused on skipped frames
        self.shared_seat_lookup = shared_seat_lookup or {}

        # Raw local seat ids actually matched to a shared global id,
        # so the pipeline can warn about any config entries left unused.
        self.matched_shared_keys: set[tuple[str, str]] = set()

        # DirectShow is only for webcams - it cannot open video files or
        # network streams, so use OpenCV's default backend for those.
        self.is_file = _is_video_file(source)
        if str(source).isdigit():
            self.cap = cv2.VideoCapture(int(source), cv2.CAP_DSHOW)
            # DirectShow defaults to 640x480, which on many webcams is a
            # CROPPED centre of the sensor (narrower view than the Windows
            # Camera app). Ask for the wide resolution from settings.yaml.
            cw = cfg.io.get("camera_width", None)
            ch = cfg.io.get("camera_height", None)
            if cw and ch:
                self.cap.set(cv2.CAP_PROP_FRAME_WIDTH, int(cw))
                self.cap.set(cv2.CAP_PROP_FRAME_HEIGHT, int(ch))
        else:
            self.cap = cv2.VideoCapture(str(source))
        if not self.cap.isOpened():
            raise RuntimeError(f"[{self.prefix}] Cannot open camera source: {source}")
        logger.info(f"[{self.prefix}] Resolution: "
                    f"{int(self.cap.get(cv2.CAP_PROP_FRAME_WIDTH))}x"
                    f"{int(self.cap.get(cv2.CAP_PROP_FRAME_HEIGHT))}")

        self.tracker = DeepSORTTracker(
            max_age=cfg.tracker.max_age,
            n_init=cfg.tracker.n_init,
            max_iou_distance=cfg.tracker.max_iou_distance,
            embedder=cfg.tracker.embedder,
        )
        self.seat_mgr = SeatManager(overlap_threshold=cfg.seats.overlap_threshold)

    def read(self):
        return self.cap.read()

    def clip_time(self) -> float:
        """Position of the last frame read, in seconds from clip start."""
        return self.cap.get(cv2.CAP_PROP_POS_MSEC) / 1000.0

    def release(self):
        self.cap.release()

    def setup_seats(self, frame) -> list[str]:
        """
        Load or draw this camera's seats, then apply IDs:
          1. If a shared_seats config entry maps this camera's raw seat id
             to a global desk, rename it to that global id.
          2. Otherwise, prefix it with this camera's name (cam0_, cam1_, ...)
             so it never collides with another camera's seats.

        The JSON on disk always keeps the RAW ids (seat_01, seat_02, ...) —
        renaming happens fresh in memory every run, so editing settings.yaml
        is enough; you never need to touch the seat JSON files by hand.
        """
        json_path = Path(self.cfg.io.output_dir) / f"seats_{self.prefix}.json"

        if json_path.exists():
            self.seat_mgr.load_from_json(json_path)
            logger.info(f"[{self.prefix}] Loaded {len(self.seat_mgr.seats)} seats "
                        f"from {json_path}")
        else:
            logger.info(f"[{self.prefix}] No saved seats - draw them for this camera "
                        f"(left-click drag, 'u'=undo, 'q'=done)")
            self.seat_mgr.draw_seats_interactive(frame)
            self.seat_mgr.save_to_json(json_path)
            logger.info(f"[{self.prefix}] Seats saved -> {json_path}")

        for seat in self.seat_mgr.seats:
            raw_id = seat.seat_id
            lookup_key = (self.prefix, raw_id)
            mapped = self.shared_seat_lookup.get(lookup_key)

            if mapped:
                seat.seat_id = mapped
                self.matched_shared_keys.add(lookup_key)
                logger.info(f"[{self.prefix}] '{raw_id}' -> shared seat '{mapped}'")
                continue

            if seat.seat_id.startswith(SHARED_SEAT_PREFIX):
                continue

            if not seat.seat_id.startswith(self.prefix):
                seat.seat_id = f"{self.prefix}_{seat.seat_id}"

        return [s.seat_id for s in self.seat_mgr.seats]


